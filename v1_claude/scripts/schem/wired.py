"""Wire-connected (label-free) schematic drawings of every cell, for reading.

The xschem schematics in xschem/ connect everything with net labels (they are generated by
scripts/gen_cells.py).  This script reads them back, places the instances with ELK (layered,
orthogonal edge routing, scripts/schem/elk_layout.js) and draws every signal net as wires.
Only the supply nets (VDD / VSS / VDDA / VDDV ...) use supply symbols at the pins.
Devices are drawn with the PDK xschem symbols (nfet_03v3, pfet_03v3, ppolyf_u_1k,
cap_mim_2f0fF) and annotated with W / L / nf / m.

The drawing is checked before it is written: every net's wires must form one connected tree that
touches all its pins, and no wire may end on, or run along, a wire of another net.

usage: python3 scripts/schem/wired.py [cell ...]     (default: all cells) -> doc/sch_wired/<cell>.png/.svg
needs node (e.g. `nix shell nixpkgs#nodejs`) with elkjs installed in scripts/schem (npm install)
"""
import json, os, re, subprocess, sys, tempfile
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
XS = os.path.join(ROOT, "xschem")
OUT = os.path.join(ROOT, "doc", "sch_wired")
PDK_SYM = os.path.join(os.environ.get("PDK_ROOT", os.path.expanduser("~/pdk")),
                       os.environ.get("PDK", "gf180mcuD"), "libs.tech", "xschem")
NODE = os.environ.get("NODE", "node")
SYMDIRS = [XS, PDK_SYM]          # chip_top.py adds its generated pad / block symbols

SUPPLY_POS = {"VDD", "VDDA", "VDDV", "DVDD", "vdd", "vdda", "vddv"}
SUPPLY_NEG = {"VSS", "DVSS", "GND", "vss", "0"}
SUPPLY = SUPPLY_POS | SUPPLY_NEG

FS = 9.0                      # device text size (schematic units)
CW = 0.6                      # char width / font size

COL = dict(dev="#1f3a93", pin="#b03a2e", wire="#1e7b34", txt="#222222", val="#8e3b00",
           sup="#7d3c98", box="#1f3a93", dot="#1e7b34", title="#000000")


# ------------------------------------------------------------------ symbols
_sym = {}


def symbol(sym):
    """Primitives and pins of an xschem symbol: dict(lines, polys, arcs, boxes, pins{name:(x,y,dir)})."""
    if sym in _sym:
        return _sym[sym]
    for d in SYMDIRS:
        p = os.path.join(d, sym)
        if os.path.exists(p):
            break
    else:
        raise FileNotFoundError(sym)
    s = dict(lines=[], polys=[], arcs=[], boxes=[], pins={}, texts=[])
    for ln in open(p):
        t = ln.split()
        if not t:
            continue
        if t[0] == "L" and t[1] == "4":
            s["lines"].append(tuple(map(float, t[2:6])))
        elif t[0] == "B" and t[1] == "5":
            x1, y1, x2, y2 = map(float, t[2:6])
            m = re.search(r"name=(\S+?)[ }]", ln)
            d = re.search(r"dir=(\w+)", ln)
            s["pins"][m.group(1)] = ((x1 + x2) / 2, (y1 + y2) / 2, d.group(1) if d else "inout")
        elif t[0] == "B" and t[1] == "4":
            s["boxes"].append(tuple(map(float, t[2:6])))
        elif t[0] == "P" and t[1] == "4":
            n = int(t[2])
            s["polys"].append(([float(v) for v in t[3:3 + 2 * n]], "fill=true" in ln))
        elif t[0] == "A" and t[1] == "4":
            s["arcs"].append(tuple(map(float, t[2:7])))
        elif t[0] == "T" and "@" not in ln and not sym.startswith("symbols/"):
            m = re.match(r"T \{(.*?)\} (\S+) (\S+) (\S+) (\S+) (\S+) (\S+)", ln)
            if m:
                s["texts"].append((m.group(1), float(m.group(2)), float(m.group(3)), int(m.group(5)), float(m.group(6))))
    _sym[sym] = s
    return s


# ------------------------------------------------------------------ schematic reader
def props(s):
    d = {}
    for m in re.finditer(r'(\w+)=("[^"]*"|\S+)', s):
        d[m.group(1)] = m.group(2).strip('"')
    return d


def read_sch(cell):
    """-> (title, ports [(name, dir)], insts [(name, sym, props, {pin: net})])"""
    pos2net, comps, ports, title = {}, [], [], cell
    for ln in open(os.path.join(XS, cell + ".sch")):
        if ln.startswith("N "):
            x1, y1, x2, y2 = map(float, ln.split()[1:5])
            pos2net[(x1, y1)] = re.search(r"lab=(\S+?)\}", ln).group(1)
        elif ln.startswith("C {"):
            m = re.match(r"C \{(\S+)\} (\S+) (\S+) (\S+) (\S+) \{(.*)\}\s*$", ln)
            sym, x, y, rot, flp, pr = m.group(1), float(m.group(2)), float(m.group(3)), m.group(4), m.group(5), props(m.group(6))
            if sym in ("devices/ipin.sym", "devices/opin.sym", "devices/iopin.sym"):
                ports.append((pr["lab"], {"ipin": "in", "opin": "out", "iopin": "inout"}[sym[8:-4]]))
            elif sym in ("devices/lab_pin.sym", "devices/title.sym"):
                pass
            else:
                assert rot == "0" and flp == "0", ln
                comps.append((sym, x, y, pr))
        elif ln.startswith("T {") and title == cell:
            title = re.match(r"T \{(.*?)\}", ln).group(1)
    insts = []
    for sym, x, y, pr in comps:
        nets = {}
        for pn, (px, py, _) in symbol(sym)["pins"].items():
            nets[pn] = pos2net[(x + px, y + py)]
        insts.append((pr["name"], sym, pr, nets))
    return title, ports, insts


# ------------------------------------------------------------------ drawing primitives (local coords)
class Node:
    """One placed thing: primitives in local coords, ports for ELK (on the bbox border)."""

    def __init__(self, nid):
        self.id = nid
        self.lines, self.polys, self.arcs, self.rects, self.texts = [], [], [], [], []
        self.dots = []
        self.ports = []          # (pid, net, x, y, side, (pin_x, pin_y))
        self.layer = None        # ELK layer constraint

    def text(self, s, x, y, size=FS, anchor="start", color=COL["txt"], bold=False):
        self.texts.append((s, x, y, size, anchor, color, bold))

    def bbox(self):
        xs, ys = [], []
        for x1, y1, x2, y2, _ in self.lines:
            xs += [x1, x2]; ys += [y1, y2]
        for pts, _, _ in self.polys:
            xs += pts[0::2]; ys += pts[1::2]
        for cx, cy, r, _, _, _ in self.arcs:
            xs += [cx - r, cx + r]; ys += [cy - r, cy + r]
        for x1, y1, x2, y2, _ in self.rects:
            xs += [x1, x2]; ys += [y1, y2]
        for s, x, y, size, anchor, _, _ in self.texts:
            w = len(s) * size * CW
            x0 = {"start": x, "middle": x - w / 2, "end": x - w}[anchor]
            xs += [x0, x0 + w]; ys += [y - size * 0.8, y + size * 0.25]
        import math
        return math.floor(min(xs) - 3), math.floor(min(ys) - 3), math.ceil(max(xs) + 3), math.ceil(max(ys) + 3)


def draw_symbol(n, sym, color=COL["dev"]):
    s = symbol(sym)
    for l in s["lines"]:
        n.lines.append(l + (color,))
    for pts, fill in s["polys"]:
        n.polys.append((pts, fill, color))
    for a in s["arcs"]:
        n.arcs.append(a + (color,))
    for b in s["boxes"]:
        n.rects.append(b + (color,))


def supply_glyph(n, net, x, y, d):
    """Supply symbol at pin (x, y), stub in direction d (dx, dy)."""
    dx, dy = d
    L = 12
    ex, ey = x + dx * L, y + dy * L
    n.lines.append((x, y, ex, ey, COL["sup"]))
    px, py = -dy, dx                       # perpendicular
    if net in SUPPLY_NEG:
        for k, h in enumerate((8, 5, 2)):
            cx, cy = ex + dx * 3 * k, ey + dy * 3 * k
            n.lines.append((cx - px * h, cy - py * h, cx + px * h, cy + py * h, COL["sup"]))
        if net not in ("VSS", "GND", "0"):
            n.text(net, ex + dx * 16, ey + dy * 16 + 3, 7, "middle", COL["sup"])
    else:
        n.lines.append((ex - px * 8, ey - py * 8, ex + px * 8, ey + py * 8, COL["sup"]))
        tx, ty = ex + dx * 9, ey + dy * 9 + (3 if dy == 0 else (0 if dy < 0 else 6))
        if dx:
            n.text(net, tx, ty, 7, "start" if dx > 0 else "end", COL["sup"])
        else:
            n.text(net, tx, ty, 7, "middle", COL["sup"])


def eng(v):
    return v.replace("e-6", "u").replace("e-9", "n").replace("e-12", "p")


def device_node(name, sym, pr, nets):
    n = Node(name)
    draw_symbol(n, sym)
    s = symbol(sym)
    kind = sym.split("/")[-1][:-4]
    m = pr.get("m", "1")
    tx = 36 if "fet" in kind else 16
    if "fet" in kind:
        n.text(name, tx, -18, FS, bold=True)
        n.text(kind, tx, -7, 7.5, color=COL["txt"])
        n.text("W=%s L=%s" % (eng(pr["W"]), eng(pr["L"])), tx, 13, FS, color=COL["val"])
        extra = []
        if pr.get("nf", "1") != "1":
            extra.append("nf=%s" % pr["nf"])
        if m != "1":
            extra.append("m=%s" % m)
        if extra:
            n.text(" ".join(extra), tx, 24, FS, color=COL["val"])
    elif kind == "ppolyf_u_1k":
        try:
            r = float(eng(pr["L"]).rstrip("u")) / float(eng(pr["W"]).rstrip("u")) * 1.0
            r /= float(m)                      # kohm, sheet resistance only (1 kohm/sq)
            rv = "%.3g Ω" % (r * 1000) if r < 1 else ("%.3g kΩ" % r if r < 1000 else "%.3g MΩ" % (r / 1000))
        except ValueError:
            rv = ""
        n.text(name, tx, -14, FS, bold=True)
        n.text(kind, tx, -4, 7.5)
        n.text("W=%s L=%s" % (eng(pr["W"]), eng(pr["L"])) + (" m=%s" % m if m != "1" else ""), tx, 9, FS, color=COL["val"])
        n.text("≈" + rv, tx, 20, 7.5, color=COL["val"])
    elif kind == "cap_mim_2f0fF":
        w, l = float(pr["W"]) * 1e6, float(pr["L"]) * 1e6
        c = 2 * w * l * float(m)
        n.text(name, 20, -14, FS, bold=True)
        n.text("cap_mim_2f0fF", 20, -4, 7.5)
        n.text("W=%gu L=%gu" % (w, l) + (" m=%s" % m if m != "1" else ""), 20, 9, FS, color=COL["val"])
        n.text("≈" + ("%.3g pF" % (c / 1000) if c >= 1000 else "%.3g fF" % c), 20, 20, 7.5, color=COL["val"])
    else:                                  # project subcircuit box
        for t, x, y, hflip, size in s["texts"]:
            n.text(t, x, y + size * 40, size * 40, "end" if hflip else "start")
        b = s["boxes"][0]
        n.text(name, (b[0] + b[2]) / 2, b[1] - 14, FS + 1, "middle", bold=True)
        n.text(kind, (b[0] + b[2]) / 2, b[1] - 3, FS, "middle", COL["val"])
    return n, kind


def side_of(kind, pn, px, py, box=False):
    if box or abs(px) >= abs(py):          # project box symbols: pins always on the left / right
        return "WEST" if px < 0 else "EAST"
    return "NORTH" if py < 0 else "SOUTH"


DIRV = {"WEST": (-1, 0), "EAST": (1, 0), "NORTH": (0, -1), "SOUTH": (0, 1)}


def build_nodes(title, ports, insts):
    nodes, netpins = [], defaultdict(list)
    supplies = {p for p, _ in ports if p in SUPPLY}
    for name, sym, pr, nets in insts:
        n, kind = device_node(name, sym, pr, nets)
        pins = symbol(sym)["pins"]
        pend = []
        for pn, (px, py, pdir) in pins.items():
            net = nets[pn]
            if "fet" in kind and pn == "B":
                if net == nets["S"]:          # bulk tied to source: classic 3-terminal look
                    sy = pins["S"][1]
                    n.lines.append((20, 0, 20, sy * 17.5 / 30, COL["dev"]))
                    n.dots.append((20, 0))
                    continue
                if net in SUPPLY:
                    # small tag: B -> rail, drawn to the right between the text lines
                    n.lines.append((20, 0, 30, 0, COL["sup"]))
                    n.text(net, 32, 3, 7, "start", COL["sup"])
                    continue
            side = side_of(kind, pn, px, py, "/" not in sym)
            if net in SUPPLY:
                supply_glyph(n, net, px, py, DIRV[side])
                continue
            pend.append((pn, net, px, py, side, pdir))
        x0, y0, x1, y1 = n.bbox()
        for pn, net, px, py, side, pdir in pend:
            bx, by = {"WEST": (x0, py), "EAST": (x1, py), "NORTH": (px, y0), "SOUTH": (px, y1)}[side]
            if (bx, by) != (px, py):
                n.lines.append((px, py, bx, by, COL["wire"]))
            pid = "%s.%s" % (name, pn)
            n.ports.append((pid, net, bx, by, side, pdir))
            netpins[net].append((pid, pdir, kind, pn))
        nodes.append(n)
    # schematic ports
    for pname, d in ports:
        if pname in SUPPLY:
            continue
        n = Node("port_" + pname)
        w = len(pname) * 10 * CW + 14
        if d == "in":
            pts = [-w, -7, -12, -7, 0, 0, -12, 7, -w, 7]
            n.polys.append((pts, False, COL["pin"]))
            n.text(pname, -w + 4, 3.5, 10, color=COL["pin"], bold=True)
            n.layer, side, px = "FIRST", "EAST", 0
        else:
            pts = [0, 0, 12, -7, w, -7, w, 7, 12, 7] if d == "out" else [0, 0, 8, -7, w - 8, -7, w, 0, w - 8, 7, 8, 7]
            n.polys.append((pts, False, COL["pin"]))
            n.text(pname, 15 if d == "out" else 10, 3.5, 10, color=COL["pin"], bold=True)
            n.layer, side, px = "LAST", "WEST", 0
        pid = n.id + ".p"
        n.ports.append((pid, pname, px, 0, side, "out" if d == "in" else "in"))
        netpins[pname].append((pid, "port_" + d, "port", pname))
        nodes.append(n)
    return nodes, netpins, sorted(supplies)


def source_of(pins, sides=None):
    """Driver of a net: schematic input port, else a device output / drain, else the first pin.
    Top-down layouts (sides given): the topmost pin, i.e. one on a SOUTH side (PMOS drain into an NMOS stack)."""
    if sides:
        for p in pins:
            if sides[p[0]] == "SOUTH":
                return p
    for p in pins:
        if p[1] == "port_in":
            return p
    for p in pins:
        if p[1] == "out" or (p[2].endswith("fet_03v3") and p[3] == "D"):
            return p
    for p in pins:
        if p[1] not in ("port_out", "port_inout"):
            return p
    return pins[0]


# ------------------------------------------------------------------ ELK
def elk(nodes, netpins, opts=None):
    g = dict(id="root", layoutOptions={
        "elk.algorithm": "layered", "elk.direction": "RIGHT", "elk.edgeRouting": "ORTHOGONAL",
        "elk.spacing.nodeNode": 30, "elk.layered.spacing.nodeNodeBetweenLayers": 40,
        "elk.spacing.edgeEdge": 9, "elk.spacing.edgeNode": 12,
        "elk.layered.spacing.edgeEdgeBetweenLayers": 9, "elk.layered.spacing.edgeNodeBetweenLayers": 12,
        "elk.layered.mergeEdges": True, "elk.layered.thoroughness": 40,
        "elk.layered.nodePlacement.strategy": "NETWORK_SIMPLEX",
        "elk.separateConnectedComponents": True, "elk.spacing.componentComponent": 60,
        "elk.padding": "[top=40,left=40,bottom=40,right=40]", **(opts or {})},
        children=[], edges=[])
    for n in nodes:
        x0, y0, x1, y1 = n.bbox()
        n.off = (x0, y0)
        c = dict(id=n.id, width=x1 - x0, height=y1 - y0, layoutOptions={"elk.portConstraints": "FIXED_POS"},
                 ports=[dict(id=pid, x=bx - x0, y=by - y0, width=0, height=0,
                             layoutOptions={"elk.port.side": side}) for pid, net, bx, by, side, _ in n.ports])
        if n.layer:
            c["layoutOptions"]["elk.layered.layering.layerConstraint"] = n.layer
        g["children"].append(c)
    sides = {pid: side for n in nodes for pid, _, _, _, side, _ in n.ports}
    k = 0
    for net, pins in netpins.items():
        if len(pins) < 2:
            continue
        s = source_of(pins, sides if g["layoutOptions"]["elk.direction"] == "DOWN" else None)
        for p in pins:
            if p is s:
                continue
            g["edges"].append(dict(id="e%d" % k, sources=[s[0]], targets=[p[0]], net=net))
            k += 1
    with tempfile.TemporaryDirectory() as td:
        fi, fo = os.path.join(td, "in.json"), os.path.join(td, "out.json")
        json.dump(g, open(fi, "w"))
        subprocess.run([NODE, os.path.join(HERE, "elk_layout.js"), fi, fo], check=True, cwd=HERE)
        r = json.load(open(fo))
    pos = {c["id"]: (c["x"], c["y"]) for c in r["children"]}
    nets = {e["id"]: e["net"] for e in g["edges"]}
    pabs = {}
    for n in nodes:
        X, Y = pos[n.id]
        for pid, net, bx, by, side, _ in n.ports:
            pabs[pid] = (X - n.off[0] + bx, Y - n.off[1] + by)
    ends = {e["id"]: (e["sources"][0], e["targets"][0]) for e in g["edges"]}
    wires = defaultdict(list)
    for e in r["edges"]:
        for sec in e.get("sections", []):
            pts = [dict(p) for p in [sec["startPoint"]] + sec.get("bendPoints", []) + [sec["endPoint"]]]
            for k, pid in ((0, ends[e["id"]][0]), (-1, ends[e["id"]][1])):
                # ELK stops the edge a few units short of a port: run a stub from the port to it
                px, py = pabs[pid]
                q, nb = pts[k], pts[1 if k == 0 else -2]
                assert abs(q["x"] - px) < 5 and abs(q["y"] - py) < 5, (pid, q, px, py)
                t = "y" if sides[pid] in ("EAST", "WEST") else "x"        # tangent axis of the port side
                tv = py if t == "y" else px
                if q[t] != tv:
                    if nb[t] == q[t]:
                        nb[t] = tv
                    q[t] = tv
                if (q["x"], q["y"]) != (px, py):
                    pts.insert(0 if k == 0 else len(pts), dict(x=px, y=py))
            for a, b in zip(pts, pts[1:]):
                if (a["x"], a["y"]) != (b["x"], b["y"]):
                    wires[nets[e["id"]]].append((a["x"], a["y"], b["x"], b["y"]))
    return pos, wires, r["width"], r["height"]


# ------------------------------------------------------------------ checks
def _r(v):
    return round(v, 2)


def seg_norm(s):
    x1, y1, x2, y2 = map(_r, s)
    return (min(x1, x2), min(y1, y2), max(x1, x2), max(y1, y2))


def on_seg(p, s):
    x, y = p
    x1, y1, x2, y2 = s
    return (x1 == x2 == x and y1 <= y <= y2) or (y1 == y2 == y and x1 <= x <= x2)


def check(wires, portpos):
    """wires {net: [seg]}, portpos {net: [(x, y)]} -> list of problems (empty = drawing is unambiguous)."""
    bad = []
    segs = {n: [seg_norm(s) for s in ss] for n, ss in wires.items()}
    for n, ss in segs.items():
        for s in ss:
            assert s[0] == s[2] or s[1] == s[3], (n, s)
    # connectivity per net
    for n, pts in portpos.items():
        if len(pts) < 2:
            continue
        ss = segs.get(n, [])
        par = list(range(len(ss)))

        def f(i):
            while par[i] != i:
                par[i] = par[par[i]]
                i = par[i]
            return i
        for i in range(len(ss)):
            for j in range(i):
                a, b = ss[i], ss[j]
                if any(on_seg(p, b) for p in ((a[0], a[1]), (a[2], a[3]))) or \
                   any(on_seg(p, a) for p in ((b[0], b[1]), (b[2], b[3]))) or \
                   (a[0] == a[2] == b[0] == b[2] and a[1] <= b[3] and b[1] <= a[3]) or \
                   (a[1] == a[3] == b[1] == b[3] and a[0] <= b[2] and b[0] <= a[2]):
                    par[f(i)] = f(j)
        roots = set()
        for p in pts:
            hit = [i for i, s in enumerate(ss) if on_seg((_r(p[0]), _r(p[1])), s)]
            if not hit:
                bad.append("%s: pin at %s not on a wire" % (n, p))
            else:
                roots.add(f(hit[0]))
        if len(roots) > 1:
            bad.append("%s: wires split into %d pieces" % (n, len(roots)))
    # other nets
    allp = [(n, s) for n, ss in segs.items() for s in ss]
    for i, (n1, a) in enumerate(allp):
        for n2, b in allp[i + 1:]:
            if n1 == n2:
                continue
            for p in ((a[0], a[1]), (a[2], a[3])):
                if on_seg(p, b):
                    bad.append("%s end %s touches %s" % (n1, p, n2))
            for p in ((b[0], b[1]), (b[2], b[3])):
                if on_seg(p, a):
                    bad.append("%s end %s touches %s" % (n2, p, n1))
            if (a[0] == a[2] == b[0] == b[2] and a[1] < b[3] and b[1] < a[3]) or \
               (a[1] == a[3] == b[1] == b[3] and a[0] < b[2] and b[0] < a[2]):
                bad.append("%s overlaps %s" % (n1, n2))
    for n1, pts in portpos.items():                # a wire running over another net's pin
        for p in pts:
            p = (_r(p[0]), _r(p[1]))
            for n2, ss in segs.items():
                if n2 != n1 and any(on_seg(p, s) for s in ss):
                    bad.append("%s runs over a %s pin at %s" % (n2, n1, p))
    return bad


def junctions(ss):
    """Points where three or more wire directions of one net meet."""
    deg = defaultdict(set)
    ss = [seg_norm(s) for s in ss]
    pts = {(s[0], s[1]) for s in ss} | {(s[2], s[3]) for s in ss}
    for p in pts:
        for s in ss:
            if not on_seg(p, s):
                continue
            if s[0] == s[2]:                 # vertical
                if s[1] < p[1]: deg[p].add("N")
                if s[3] > p[1]: deg[p].add("S")
            else:
                if s[0] < p[0]: deg[p].add("W")
                if s[2] > p[0]: deg[p].add("E")
    return [p for p, d in deg.items() if len(d) >= 3]


# ------------------------------------------------------------------ SVG
def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def svg(nodes, pos, wires, W, H, title, notes, extra_dots=()):
    top = 60 + 14 * len(notes)
    W = max(W, 40 + 13.5 * len(title), 40 + 6.5 * max(len(t) for t in notes))
    o = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 %d %d %d" '
         'font-family="DejaVu Sans, Arial, sans-serif">' % (W, H + top, -top, W, H + top),
         '<rect x="0" y="%d" width="%d" height="%d" fill="white"/>' % (-top, W, H + top),
         '<text x="20" y="%d" font-size="22" font-weight="bold" fill="%s">%s</text>' % (-top + 30, COL["title"], esc(title))]
    for i, t in enumerate(notes):
        o.append('<text x="20" y="%d" font-size="11" fill="#444">%s</text>' % (-top + 50 + 14 * i, esc(t)))
    for net, ss in wires.items():
        for x1, y1, x2, y2 in ss:
            o.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="1.3"/>' % (x1, y1, x2, y2, COL["wire"]))
        for x, y in junctions(ss):
            o.append('<circle cx="%.1f" cy="%.1f" r="2.6" fill="%s"/>' % (x, y, COL["dot"]))
    for x, y in extra_dots:
        o.append('<circle cx="%.1f" cy="%.1f" r="2.6" fill="%s"/>' % (x, y, COL["dot"]))
    for n in nodes:
        X, Y = pos[n.id]
        ox, oy = X - n.off[0], Y - n.off[1]
        o.append('<g transform="translate(%.2f,%.2f)">' % (ox, oy))
        for x1, y1, x2, y2, c in n.lines:
            o.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="%s" stroke-width="1.3"/>' % (x1, y1, x2, y2, c))
        for x1, y1, x2, y2, c in n.rects:
            o.append('<rect x="%g" y="%g" width="%g" height="%g" fill="#f4f7fc" stroke="%s" stroke-width="1.5"/>'
                     % (min(x1, x2), min(y1, y2), abs(x2 - x1), abs(y2 - y1), c))
        for pts, fill, c in n.polys:
            o.append('<polygon points="%s" fill="%s" stroke="%s" stroke-width="1.2"/>'
                     % (" ".join("%g" % v for v in pts), c if fill else "white", c))
        for cx, cy, r, a, b, c in n.arcs:
            if b >= 360:
                o.append('<circle cx="%g" cy="%g" r="%g" fill="none" stroke="%s" stroke-width="1.3"/>' % (cx, cy, r, c))
        for x, y in n.dots:
            o.append('<circle cx="%g" cy="%g" r="2" fill="%s"/>' % (x, y, COL["dev"]))
        for s, x, y, size, anchor, c, bold in n.texts:
            o.append('<text x="%g" y="%g" font-size="%g" text-anchor="%s" fill="%s"%s>%s</text>'
                     % (x, y, size, anchor, c, ' font-weight="bold"' if bold else "", esc(s)))
        o.append("</g>")
    o.append("</svg>")
    return "\n".join(o)


def to_png(svgtext, path, W):
    import cairosvg
    scale = min(3.0, 14000.0 / W)
    cairosvg.svg2png(bytestring=svgtext.encode(), write_to=path, scale=scale, background_color="white")


# ------------------------------------------------------------------ main
def render(cell, title=None, ports=None, insts=None, notes=(), opts=None, out=None):
    if insts is None:
        title, ports, insts = read_sch(cell)
    nodes, netpins, supplies = build_nodes(title, ports, insts)
    if opts is None:     # transistor level: top-down (VDD above, VSS below); block level: left to right
        nsub = sum(1 for i in insts if "/" not in i[1])
        opts = {"elk.direction": "RIGHT" if 2 * nsub > len(insts) else "DOWN"}
    pos, wires, W, H = elk(nodes, netpins, opts)
    portpos = defaultdict(list)
    for n in nodes:
        X, Y = pos[n.id]
        for pid, net, bx, by, side, _ in n.ports:
            portpos[net].append((X - n.off[0] + bx, Y - n.off[1] + by))
    bad = check(wires, portpos)
    # single-pin nets: mark them (no wire)
    for net, pts in portpos.items():
        if len(pts) == 1:
            for n in nodes:
                for pid, nn, bx, by, side, _ in n.ports:
                    if nn == net:
                        dx, dy = DIRV[side]
                        n.lines.append((bx, by, bx + 8 * dx, by + 8 * dy, COL["wire"]))
                        n.text(net + " (n.c.)", bx + 10 * dx, by + 10 * dy + 3, 7, "start" if dx >= 0 else "end", COL["wire"])
    notes = list(notes)
    if supplies:
        notes.append("Supply pins: %s (drawn as supply symbols at each device pin; ground symbol = VSS)" % ", ".join(supplies))
    notes.append("Devices: GF180MCU PDK (nfet_03v3 / pfet_03v3 / ppolyf_u_1k / cap_mim_2f0fF); W, L in metres "
                 "(u = um); bulk drawn to source where tied, otherwise tagged.")
    s = svg(nodes, pos, wires, W, H, title, notes)
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(out or OUT, cell + ".svg"), "w").write(s)
    to_png(s, os.path.join(out or OUT, cell + ".png"), W)
    return bad, len(insts), W, H


